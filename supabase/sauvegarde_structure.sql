-- FiltroPro — sauvegarde de la STRUCTURE de la base + taille (15/11/2026, BIBLE §8.24)
-- La sauvegarde quotidienne (scripts/sauvegarde.mjs) copie les DONNÉES. Si le projet Supabase était perdu,
-- il faudrait aussi recréer les tables, règles, fonctions et vues : schema_complet() les écrit en SQL,
-- et la sauvegarde l'enregistre chaque jour dans backups/AAAA-MM-JJ/structure.sql.
-- taille_base() : taille de la base (plan gratuit = 500 Mo maximum) → notée dans manifeste.json.
-- Lecture seule, réservé à la clé serveur (service_role). Idempotent : peut être recollé sans risque.

create or replace function public.taille_base() returns bigint
language sql security definer set search_path = '' as $$
  select pg_catalog.pg_database_size(pg_catalog.current_database())
$$;
revoke all on function public.taille_base() from public, anon, authenticated;
grant execute on function public.taille_base() to service_role;

create or replace function public.schema_complet() returns text
language plpgsql security definer set search_path = '' as $$
declare
  sortie text := '-- Structure FiltroPro générée le ' || pg_catalog.now()::text || E' par public.schema_complet()\n'
              || E'-- Ordre : tables, contraintes, index, fonctions, vues, déclencheurs, RLS + règles, droits, buckets photos.\n\n';
  r record;
begin
  -- 1) Tables et colonnes
  for r in
    select c.oid, c.relname from pg_catalog.pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p') order by c.relname
  loop
    sortie := sortie || 'create table if not exists public.' || quote_ident(r.relname) || E' (\n' ||
      coalesce((
        select string_agg('  ' || quote_ident(a.attname) || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
          || case when a.attidentity = 'a' then ' generated always as identity'
                  when a.attidentity = 'd' then ' generated by default as identity' else '' end
          || case when a.attgenerated = 's' then ' generated always as (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') stored'
                  when d.adbin is not null then ' default ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) else '' end
          || case when a.attnotnull then ' not null' else '' end, E',\n' order by a.attnum)
        from pg_catalog.pg_attribute a
        left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
        where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped), '')
      || E'\n);\n';
  end loop;

  -- 2) Contraintes (clés, uniques, contrôles ; liens entre tables en dernier)
  sortie := sortie || E'\n';
  for r in
    select conrelid::regclass::text as t, conname, pg_catalog.pg_get_constraintdef(oid) as def
    from pg_catalog.pg_constraint
    where connamespace = 'public'::regnamespace and contype in ('p', 'u', 'c', 'x', 'f') and conrelid <> 0
    order by case contype when 'f' then 1 else 0 end, conrelid::regclass::text, conname
  loop
    sortie := sortie || 'alter table ' || r.t || ' add constraint ' || quote_ident(r.conname) || ' ' || r.def || E';\n';
  end loop;

  -- 3) Index (sauf ceux créés par les contraintes)
  sortie := sortie || E'\n';
  for r in
    select i.indexdef from pg_catalog.pg_indexes i
    where i.schemaname = 'public'
      and not exists (select 1 from pg_catalog.pg_constraint c where c.conname = i.indexname and c.connamespace = 'public'::regnamespace)
    order by i.tablename, i.indexname
  loop
    sortie := sortie || r.indexdef || E';\n';
  end loop;

  -- 4) Fonctions (est_autorise, decrement_stock, …)
  sortie := sortie || E'\n';
  for r in
    select pg_catalog.pg_get_functiondef(p.oid) as def from pg_catalog.pg_proc p
    where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p') order by p.proname
  loop
    sortie := sortie || r.def || E';\n\n';
  end loop;

  -- 5) Vues (product_vehicles, prospects_par_jour, …)
  for r in
    select c.relname, pg_catalog.pg_get_viewdef(c.oid, true) as def, c.reloptions from pg_catalog.pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'v' order by c.relname
  loop
    sortie := sortie || 'create or replace view public.' || quote_ident(r.relname)
      || coalesce(' with (' || array_to_string(r.reloptions, ', ') || ')', '') || E' as\n' || r.def || E'\n\n';
  end loop;

  -- 6) Déclencheurs
  for r in
    select pg_catalog.pg_get_triggerdef(t.oid) as def from pg_catalog.pg_trigger t
    join pg_catalog.pg_class c on c.oid = t.tgrelid
    where c.relnamespace = 'public'::regnamespace and not t.tgisinternal
  loop
    sortie := sortie || r.def || E';\n';
  end loop;

  -- 7) Sécurité : RLS + règles (tables publiques et photos du stockage)
  sortie := sortie || E'\n';
  for r in
    select c.relname from pg_catalog.pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relrowsecurity order by c.relname
  loop
    sortie := sortie || 'alter table public.' || quote_ident(r.relname) || E' enable row level security;\n';
  end loop;
  for r in
    select * from pg_catalog.pg_policies where schemaname in ('public', 'storage') order by schemaname, tablename, policyname
  loop
    sortie := sortie || 'create policy ' || quote_ident(r.policyname) || ' on ' || quote_ident(r.schemaname) || '.' || quote_ident(r.tablename)
      || ' as ' || r.permissive || ' for ' || r.cmd || ' to ' || array_to_string(r.roles, ', ')
      || coalesce(' using (' || r.qual || ')', '') || coalesce(' with check (' || r.with_check || ')', '') || E';\n';
  end loop;

  -- 8) Droits du public (anon) et de l'équipe (authenticated)
  sortie := sortie || E'\n';
  for r in
    select grantee, table_name, string_agg(privilege_type, ', ' order by privilege_type) as privs
    from information_schema.role_table_grants
    where table_schema = 'public' and grantee in ('anon', 'authenticated')
    group by grantee, table_name order by table_name, grantee
  loop
    sortie := sortie || 'grant ' || r.privs || ' on public.' || quote_ident(r.table_name) || ' to ' || r.grantee || E';\n';
  end loop;
  for r in
    select grantee, table_name, privilege_type, string_agg(quote_ident(column_name), ', ' order by column_name) as cols
    from information_schema.column_privileges
    where table_schema = 'public' and grantee = 'anon'
    group by grantee, table_name, privilege_type order by table_name
  loop
    sortie := sortie || 'grant ' || r.privilege_type || ' (' || r.cols || ') on public.' || quote_ident(r.table_name) || ' to ' || r.grantee || E';\n';
  end loop;

  -- 9) Buckets de photos (Storage)
  sortie := sortie || E'\n';
  for r in select id, name, public from storage.buckets order by id loop
    sortie := sortie || 'insert into storage.buckets (id, name, public) values (' || quote_literal(r.id) || ', ' || quote_literal(r.name) || ', ' || r.public
      || E') on conflict (id) do nothing;\n';
  end loop;

  return sortie;
end $$;
revoke all on function public.schema_complet() from public, anon, authenticated;
grant execute on function public.schema_complet() to service_role;

notify pgrst, 'reload schema';

-- ============================================================
-- TABLE VEHICULES
-- ============================================================
create table if not exists public.vehicules (
  id          uuid primary key default gen_random_uuid(),
  marque      text not null,
  modele      text not null,
  annee_debut integer not null,
  annee_fin   integer,
  motorisation text not null,
  carburant   text not null check (carburant in ('diesel','essence','hybride')),
  cylindree   text
);

create index if not exists idx_vehicules_marque on public.vehicules(marque);
create index if not exists idx_vehicules_modele on public.vehicules(modele);

alter table public.vehicules enable row level security;
create policy "allow all vehicules" on public.vehicules for all using (true) with check (true);

-- ============================================================
-- TABLE COMPATIBILITES
-- ============================================================
create table if not exists public.compatibilites (
  id          uuid primary key default gen_random_uuid(),
  product_id  uuid not null references public.products(id) on delete cascade,
  vehicule_id uuid not null references public.vehicules(id) on delete cascade,
  unique(product_id, vehicule_id)
);

create index if not exists idx_compat_product on public.compatibilites(product_id);
create index if not exists idx_compat_vehicule on public.compatibilites(vehicule_id);

alter table public.compatibilites enable row level security;
create policy "allow all compatibilites" on public.compatibilites for all using (true) with check (true);

